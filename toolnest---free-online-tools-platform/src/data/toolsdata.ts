export function getToolBySlug(slug: string): ToolDefinition | undefined {
  return toolsData.find((t) => t.slug === slug);
}

export function getToolsByCategory(category: string): ToolDefinition[] {
  if (category === 'all') return toolsData;
  return toolsData.filter((t) => t.category === category || t.subCategory === category);
}

export function getPopularTools(limit = 8): ToolDefinition[] {
  return [...toolsData].sort((a, b) => b.popularity - a.popularity).slice(0, limit);
}

export function getTrendingTools(limit = 6): ToolDefinition[] {
  return toolsData.filter((t) => t.isTrending).slice(0, limit);
}
